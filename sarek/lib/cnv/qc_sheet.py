from os.path import dirname, abspath, basename as get_basename
import asyncio
import subprocess
import io
import numpy as np
import polars as pl
import narwhals.stable.v2 as nw
import matplotlib.pyplot as plt

MOS_FILES_COL = "mos_files"
CNR_FILES_COL = "cnr_files"
CNS_FILES_COL = "cns_files"
SAMPLE_COL = "sample"
MTC_COL = "Mean Target Coverage (MTC)"
MAD_COL = "mad"

THRESHOLD_LEGEND = "Pink indicates low sensitivity."
THRESHOLD_LEGEND2 = "Low sensitivity thresholds based on paper: Chandramohan et al., 2022"
THRESHOLD_LEGEND3 = "https://doi.org/10.1016/j.jmoldx.2022.03.011"
MAD_BAD_THRESHOLD = 0.35
MTC_BAD_THRESHOLD = 50.0
BAD_COLOR = "hotpink"
GOOD_COLOR = "darkblue"


def organize_qc_files(
    mos_files: list[str],
    cnr_files: list[str],
    cns_files: list[str]
) -> nw.DataFrame:
  """
  Organizes all the files by sample/basename into a DataFrame.
  """
  mos_df = nw.from_native(pl.DataFrame({MOS_FILES_COL: mos_files}))
  cnr_df = nw.from_native(pl.DataFrame({CNR_FILES_COL: cnr_files}))
  cns_df = nw.from_native(pl.DataFrame({CNS_FILES_COL: cns_files}))
  mos_df = mos_df.with_columns(nw.col(MOS_FILES_COL).str.replace(".recal.mosdepth.summary.txt", "").alias(SAMPLE_COL))
  cnr_df = cnr_df.with_columns(nw.col(CNR_FILES_COL).str.replace(".cnr", "").alias(SAMPLE_COL))
  cns_df = cns_df.with_columns(nw.col(CNS_FILES_COL).str.replace(".cns", "").alias(SAMPLE_COL))
  mos_df = mos_df.to_native().with_columns(
      pl.col(SAMPLE_COL).map_elements(lambda filename: get_basename(filename)).alias(SAMPLE_COL)
  )
  cnr_df = cnr_df.to_native().with_columns(
      pl.col(SAMPLE_COL).map_elements(lambda filename: get_basename(filename)).alias(SAMPLE_COL)
  )
  cns_df = cns_df.to_native().with_columns(
      pl.col(SAMPLE_COL).map_elements(lambda filename: get_basename(filename)).alias(SAMPLE_COL)
  )
  all_qc_files = mos_df.join(cnr_df, on=SAMPLE_COL, how="full", suffix="_cnr", coalesce=True)
  all_qc_files = all_qc_files.join(cns_df, on=SAMPLE_COL, how="full", suffix="_cns", coalesce=True)
  all_qc_files = nw.from_native(all_qc_files)
  return all_qc_files


def get_one_sample_mtc(one_mos_file: str) -> tuple[str, float]:
  mosdepth_summary = nw.from_native(pl.read_csv(one_mos_file, separator="\t", has_header=True, row_index_offset=0))
  # The last row has the mean target average
  mean_target_coverage = mosdepth_summary.tail(1).item(0, "mean")
  return (one_mos_file, mean_target_coverage)


async def run_cnvkit_metrics(just_cnr_cns: nw.DataFrame, bucket_dir) -> nw.DataFrame:
  """
  Run the cnvkit.py metrics command to get metrics.
  :param just_cnr_cns nw.DataFrame: A DataFrame with columns cnr_files cns_files that are sorted by sample name and
      correspond to each other. Also, the columns should have no null values.
  """
  abs_bucket_dir = abspath(bucket_dir)
  cnr_files: list = just_cnr_cns.get_column(CNR_FILES_COL).to_list()
  cns_files: list = just_cnr_cns.get_column(CNS_FILES_COL).to_list()
  cnvkit_command = ["cnvkit.py", "metrics"] + cnr_files + ["-s"] + cns_files
  docker_command = (
      ["docker", "run", "-v", f"{abs_bucket_dir}:{abs_bucket_dir}", "-w", abs_bucket_dir,
       "quay.io/biocontainers/cnvkit:0.9.10--pyhdfd78af_0"] + cnvkit_command
  )
  print(f"Running command: {" ".join(docker_command)}")
  cnvkit_stream = subprocess.run(docker_command, capture_output=True, check=True, text=True)
  cnvkit_metrics = nw.from_native(pl.DataFrame({}))
  if cnvkit_stream.stdout:
    cnvkit_metrics = pl.read_csv(io.StringIO(cnvkit_stream.stdout), has_header=True, separator="\t")
  return nw.from_native(cnvkit_metrics)


async def get_qc_metrics(
    mos_files: list[str],
    cnr_files: list[str],
    cns_files: list[str],
    bucket_dir=""
) -> nw.DataFrame:
  """
  Gather all the QC Metrics for the CNV report. Some of these will be generated by a docker command `cnvkit.py metrics`
  """
  if not bucket_dir:
    bucket_dir = dirname(dirname(dirname(mos_files[0])))
  all_qc_files = organize_qc_files(mos_files, cnr_files, cns_files)
  just_cnr_cns = all_qc_files.select(nw.col(CNR_FILES_COL), nw.col(CNS_FILES_COL))
  just_cnr_cns = just_cnr_cns.drop_nulls()
  cnvkit_task = asyncio.create_task(run_cnvkit_metrics(just_cnr_cns, bucket_dir))
  mtc_results = []
  for one_mos_file in mos_files:
    one_sample_mtc = get_one_sample_mtc(one_mos_file)
    mtc_results.append(one_sample_mtc)
  mtc_df = nw.from_native(pl.DataFrame(mtc_results, orient="row", schema=[MOS_FILES_COL, MTC_COL]))
  all_qc_data = all_qc_files.join(mtc_df, MOS_FILES_COL, how="full")
  cnvkit_metrics = await cnvkit_task
  cnvkit_metrics = cnvkit_metrics.rename({"sample": CNR_FILES_COL})
  all_qc_data = all_qc_data.join(cnvkit_metrics, on=CNR_FILES_COL, how="full")
  columns_to_select = cnvkit_metrics.columns
  columns_to_select.remove(CNR_FILES_COL)
  columns_to_select = [SAMPLE_COL, MTC_COL] + columns_to_select
  qc_metrics_without_filenames = all_qc_data.select(columns_to_select)
  return qc_metrics_without_filenames


def graph_mtc(qc_metrics: nw.DataFrame) -> io.BytesIO:
  mtc_col = qc_metrics.get_column(MTC_COL)
  binwidth = min(50.0, max(mtc_col) / 5.0)
  max_mtc_graph = max(mtc_col) + binwidth
  if max_mtc_graph >= 20.0 and max_mtc_graph <= 60.0:
    max_mtc_graph = 60.0
  mtc_hist_bins = np.arange(0.0, max_mtc_graph, binwidth)
  (n, bins, patches) = plt.hist(mtc_col, bins=mtc_hist_bins, color=GOOD_COLOR)
  plt.xticks(mtc_hist_bins[:-1])
  max_n = max(n)
  plt.ylabel("Number of Samples")
  plt.xlabel("Mean Target Coverage (MTC)")
  plt.xlim(0, None)
  if max_mtc_graph >= 50.0:
    plt.plot([MTC_BAD_THRESHOLD, MTC_BAD_THRESHOLD], [0, max_n], color=BAD_COLOR, linestyle="dashed")
  plt.axvspan(0, MTC_BAD_THRESHOLD, facecolor=BAD_COLOR, alpha=0.1)
  for index_bin, one_bin in enumerate(bins[:-1]):
    if one_bin < MTC_BAD_THRESHOLD:
      patches[index_bin].set_facecolor(BAD_COLOR)
  mtc_hist_mem_loc = io.BytesIO()
  plt.savefig(mtc_hist_mem_loc, format="png")
  plt.close()
  return mtc_hist_mem_loc


def graph_mad(qc_metrics: nw.DataFrame) -> io.BytesIO:
  mad_col = qc_metrics.get_column(MAD_COL)
  binwidth = 0.025
  max_mad_graph = max(max(mad_col) + binwidth, 0.4)
  mad_hist_bins = np.arange(0.0, max_mad_graph, binwidth)
  (n, bins, patches) = plt.hist(mad_col, bins=mad_hist_bins, color=GOOD_COLOR)
  max_n = max(n)
  plt.ylabel("Number of Samples")
  plt.xlabel("Median Absolute Deviation (MAD)")
  plt.xlim(0, max_mad_graph)
  plt.plot([MAD_BAD_THRESHOLD, MAD_BAD_THRESHOLD], [0, max_n], color=BAD_COLOR, linestyle="dashed")
  plt.axvspan(MAD_BAD_THRESHOLD, max_mad_graph, facecolor=BAD_COLOR, alpha=0.1)
  for index_bin, one_bin in enumerate(bins[:-1]):
    if one_bin > MAD_BAD_THRESHOLD:
      patches[index_bin].set_facecolor(BAD_COLOR)
  mad_hist_mem_loc = io.BytesIO()
  plt.savefig(mad_hist_mem_loc, format="png")
  plt.close()
  return mad_hist_mem_loc


async def graph_qc_metrics(qc_metrics: nw.DataFrame) -> tuple[io.BytesIO, io.BytesIO]:
  """
  Create 2 QC graphs:
  1. Mean target coverage (MTC) histogram
  2. Median absolute deviation (MAD) histogram.
  """
  mtc_hist_mem_loc = graph_mtc(qc_metrics)
  mad_hist_mem_loc = graph_mad(qc_metrics)
  return (mtc_hist_mem_loc, mad_hist_mem_loc)
