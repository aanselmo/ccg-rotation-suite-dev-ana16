MOS_FILES_COL = "mos_files"
CNR_FILES_COL = "cnr_files"
CNS_FILES_COL = "cns_files"
BASENAME_COL = "basename"
MTC_COL = "Mean Target Coverage (MTC)"


def organize_qc_files(
    mos_files: list[str],
    cnr_files: list[str],
    cns_files: list[str]
) -> nw.LazyFrame:
  """
  Organizes all the files by sample/basename into a DataFrame.
  """
  mos_df = nw.from_native(pl.LazyFrame({MOS_FILES_COL: mos_files}))
  cnr_df = nw.from_native(pl.LazyFrame({CNR_FILES_COL: cnr_files}))
  cns_df = nw.from_native(pl.LazyFrame({CNS_FILES_COL: cns_files}))
  mos_df = mos_df.with_columns(basename=nw.col(mos_df.col(
      MOS_FILES_COL).str.replace(".recal.mosdepth.summary.txt", "")))
  cnr_df = cnr_df.with_columns(basename=nw.col(cnr_df.col(CNR_FILES_COL).str.replace(".cnr", "")))
  cns_df = cns_df.with_columns(basename=nw.col(cns_df.col(CNS_FILES_COL).str.replace(".cns", "")))
  all_qc_files = mos_df.join(cnr_df, BASENAME_COL, how="full")
  all_qc_files = all_qc_files.join(cnr_df, BASENAME_COL, how="full")
  return all_qc_files.collect()


def get_one_sample_mtc(one_mos_file: str) -> tuple[str, float]:
  mosdepth_summary = nw.from_native(pl.scan_csv(one_mos_file, separator="\t", has_header=True, row_index_offset=0))
  # The last row has the mean target average
  mean_target_coverage = mosdepth_summary.tail(1).item(0, "mean")
  return (one_mos_file, mean_target_coverage)


async def run_cnvkit_metrics(just_cnr_cns: nw.LazyFrame, bucket_dir) -> nw.LazyFrame:
  """
  Run the cnvkit.py metrics command to get metrics.
  :param just_cnr_cns nw.LazyFrame: A DataFrame with columns cnr_files cns_files that are sorted by sample name and
      correspond to each other. Also, the columns should have no null values.
  """
  cnr_files: list = just_cnr_cns.get_column(CNR_FILES_COL).collect()
  cns_files: list = just_cnr_cns.get_column(CNS_FILES_COL).collect()
  cnvkit_command = ["cnvkit.py"] + cnr_files + ["-s"] + cns_files
  docker_command = (
      ["docker", "run", "-v", f"{bucket_dir}:{bucket_dir}", "-w", bucket_dir, "quay.io/biocontainers/cnvkit"]
      + cnvkit_command
  )
  print(f"Running command: {docker_command.join(" ")}")
  cnvkit_stream = subprocess.run(docker_command, capture_output=True, text=True)
  cnvkit_metrics = nw.from_native(pl.LazyFrame({}))
  if cnvkit_stream.stdout:
    cnvkit_metrics = pl.scan_csv(io.StringIO(cnvkit_stream.stdout), has_header=True, separator="\t")
  return cnvkit_metrics.collect()


async def get_qc_metrics(
    mos_files: list[str],
    cnr_files: list[str],
    cns_files: list[str],
    total_processes=3,
    bucket_dir=""
) -> nw.LazyFrame:
  """
  Gather all the QC Metrics for the CNV report. Some of these will be generated by a docker command `cnvkit.py metrics`
  """
  # qc_metrics = columns(sample_name, MTC, cnvkit.py metrics)
  # Spawn is a recommendation from the polars website: https://docs.pola.rs/user-guide/misc/multiprocessing/
  if not bucket_dir:
    bucket_dir = dirname(dirname(dirname(mos_files[0])))
  all_qc_files = organize_qc_files(mos_files, cnr_files, cns_files)
  just_cnr_cns = all_qc_files.select(nw.col(CNR_FILES_COL), nw.col(CNS_FILES_COL))
  just_cnr_cns = just_cnr_cns.drop_nulls().collect()
  cnvkit_task = asyncio.create_task(run_cnvkit_metrics(just_cnr_cns, bucket_dir))
  mtc_results = []
  with ProcessPoolExecutor(max_workers=total_processes, mp_context=mp.get_context("spawn")) as read_files_pool:
    mtc_results = list(read_files_pool.map(get_one_sample_mtc, mos_files))
  mtc_df = nw.from_native(pl.LazyFrame(mtc_results, orient="row", schema=[MOS_FILES_COL, MTC_COL]))
  all_qc_data = all_qc_files.join(mtc_df, MOS_FILES_COL, how="full")
  cnvkit_metrics = await cnvkit_task
  cnvkit_metrics = cnvkit_metrics.rename({"sample": CNR_FILES_COL})
  all_cols_except_filename = cnvkit_metrics.columns.remove(CNR_FILES_COL)
  all_qc_data = all_qc_files.join(cnvkit_metrics, on=CNR_FILES_COL, how="full")
  qc_metrics_without_filenames = all_qc_data.select(nw.col([BASENAME_COL, MTC_COL, all_cols_except_filename]))
  return qc_metrics_without_filenames


