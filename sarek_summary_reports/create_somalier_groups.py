#!/usr/local/miniforge3/bin/python

"""
Use this script to create the groups file for somalier relate.
"""

__docformat__ = "reStructuredText"
__credits__ = ["Neil A. Patel"]


import argparse
import warnings
from datetime import date
from os import makedirs
from os.path import join
import polars as pl
from lib.common import append_common_args, DEFAULT_CSV_OUTPUT


DEFAULT_GROUPS_FILE_ENDING = "somalier_groups.csv"
PATIENT_COL = "patient"
SAMPLE_COL = "sample"

def setup_arguments():
  parser = argparse.ArgumentParser(description=(
      "Use this script to create the groups file for somalier relate."
  ))
  project_arg = append_common_args(parser)
  project_arg.required = True
  parser.add_argument("-r", "--recalibrated-csv", dest="recalibrated_csv", type=str, default="", required=True,
                      help="The path to the recalibrated.csv file generated by Sarek.")
  return parser.parse_args()


def get_output_file_name(args, file_ending: str, default_file_name: str) -> tuple[str, str]:
  project_csv_dir = "csv"
  output_file_name = args.output_file_name
  today = date.today().strftime('%Y%m%d')
  project_code = "test"
  if output_file_name == default_file_name and args.project_code:
    project_code = args.project_code
    makedirs(project_csv_dir, exist_ok=True)
    output_file_name = join(project_csv_dir, f"{today}_{project_code.lower()}_{file_ending}")
  return (project_code, output_file_name)


def main():
  """
  Runs the whole script.
  """
  args = setup_arguments()
  (project_code, output_file_name) = get_output_file_name(
      args,
      DEFAULT_GROUPS_FILE_ENDING,
      DEFAULT_CSV_OUTPUT
  )
  patients_and_samples = pl.read_csv(args.recalibrated_csv, columns=[PATIENT_COL, SAMPLE_COL])
  patients_and_samples = patients_and_samples.group_by(PATIENT_COL).agg(pl.col(SAMPLE_COL))
  patients_and_samples = patients_and_samples.select(
      # This is how nextflow's somalier pipeline runs it. patient_sample
      pl.col(SAMPLE_COL).list.eval(pl.col(PATIENT_COL) + "_" + pl.element())
  )
  patients_and_samples = patients_and_samples.select(pl.col(SAMPLE_COL).explode())
  patients_and_samples.write_csv(output_file_name)



if __name__ == "__main__":
  main()
